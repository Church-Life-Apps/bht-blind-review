create table if not exists public.votes (
  id bigserial primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  verse_id text not null references public.verse_ids(id),
  choice text not null check (choice in ('A','B')),
  reason text check (reason is null or char_length(reason) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, verse_id)
);

alter table public.votes enable row level security;
alter table public.verse_ids enable row level security;

-- Signed-in reviewers can read, add and change only their own votes. One row per person per verse is enforced by the unique key.
create policy "read own votes" on public.votes for select to authenticated using (user_id = auth.uid());
create policy "insert own votes" on public.votes for insert to authenticated with check (user_id = auth.uid());
create policy "update own votes" on public.votes for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists votes_touch on public.votes;
create trigger votes_touch before update on public.votes for each row execute function public.touch_updated_at();

-- Tally for the owner. Read it in the dashboard SQL editor, it is not exposed to the site.
create or replace view public.vote_tally with (security_invoker = true) as
  select verse_id, count(*) filter (where choice='A') as a_votes, count(*) filter (where choice='B') as b_votes,
         count(reason) filter (where reason <> '') as reasons
  from public.votes group by verse_id;
revoke all on public.vote_tally from anon, authenticated;
